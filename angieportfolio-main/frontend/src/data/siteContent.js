const translateDeep = (value, dictionary) => {
  if (Array.isArray(value)) return value.map((item) => translateDeep(item, dictionary));
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, translateDeep(item, dictionary)]),
    );
  }
  if (typeof value === "string") return dictionary[value] || value;
  return value;
};

const contentCache = {};

export const getSiteContent = (language = "es") => {
  const safeLanguage = language === "en" ? "en" : "es";
  if (!contentCache[safeLanguage]) {
    const content =
      safeLanguage === "es"
        ? translateDeep(siteContentBase, spanishCopy)
        : translateDeep(siteContentBase, {});
    content.meta.cvUrl = safeLanguage === "es" ? content.meta.cvUrlEs : content.meta.cvUrlEn;
    content.footer.copyright =
      safeLanguage === "es"
        ? `© ${new Date().getFullYear()} Angélica Jiménez — Todos los derechos reservados.`
        : `© ${new Date().getFullYear()} Angélica Jiménez — All rights reserved.`;
    content.ui = uiText[safeLanguage];
    contentCache[safeLanguage] = content;
  }
  return contentCache[safeLanguage];
};

